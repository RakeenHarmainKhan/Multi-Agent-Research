from app.tools.output import ReportGenerator


def test_renders_headings_and_footer():
    html = ReportGenerator.markdown_to_html("## Executive Summary\n\nHello")
    assert "<h2" in html and "Executive Summary" in html
    assert "Generated by MARA Research Assistant" in html


def test_renders_tables():
    html = ReportGenerator.markdown_to_html("| a | b |\n|---|---|\n| 1 | 2 |")
    assert "<table>" in html


def test_includes_print_button():
    assert "window.print()" in ReportGenerator.markdown_to_html("x")
